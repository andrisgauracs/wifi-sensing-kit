"""Build the sensing firmware for your boards.

  python firmware/build.py

1. downloads RuView's esp32-csi-node firmware at v0.8.8 (MIT) into firmware/.build/
2. applies ruview-v0.8.8-kit.patch (LED colour per board + board-to-board links)
3. writes kit_config.h from config.yaml (router + board MACs, LED colours)
4. builds with ESP-IDF (the path in config.yaml)
"""
import os, subprocess, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import kitconfig  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.join(HERE, ".build")
REPO = os.path.join(WORK, "RuView")
PROJ = os.path.join(REPO, "firmware", "esp32-csi-node")
TAG = "v0.8.8-esp32"
PATCH = os.path.join(HERE, "ruview-v0.8.8-kit.patch")


def run(cmd, **kw):
    print("$", cmd if isinstance(cmd, str) else " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True, **kw)


def fetch():
    if not os.path.exists(REPO):
        os.makedirs(WORK, exist_ok=True)
        run(["git", "clone", "--depth", "1", "--branch", TAG, "--filter=blob:none", "--sparse",
             "https://github.com/ruvnet/RuView.git", REPO])
        run(["git", "sparse-checkout", "set", "firmware/esp32-csi-node"], cwd=REPO)
    # apply the patch once (skip if it's already in)
    applied = subprocess.run(["git", "apply", "--reverse", "--check", PATCH], cwd=REPO, capture_output=True).returncode == 0
    if not applied:
        run(["git", "apply", PATCH], cwd=REPO)


def kit_header(c):
    macs = [c["router_bssid"]] + [b["mac"] for b in c["boards"]]
    macs = [m for m in macs if kitconfig.MAC_RE.match(m)]
    rows = ", \\\n".join("    {" + ", ".join(f"0x{x}" for x in m.split(":")) + "}" for m in macs)
    rgb = ", ".join("{%d, %d, %d, %d}" % (b["id"], *kitconfig.COLOURS[b["colour"]]) for b in c["boards"])
    with open(os.path.join(PROJ, "main", "kit_config.h"), "w") as f:
        f.write("/* Generated by wifi-sensing-kit firmware/build.py from config.yaml — do not edit. */\n#pragma once\n")
        f.write(f"#define LINK_MACS {{ \\\n{rows} \\\n}}\n#define KIT_NODE_RGB {{ {rgb} }}\n")
    if c["router_bssid"] in ("", "aa:bb:cc:dd:ee:ff"):
        print("note: router_bssid isn't set — boards will only measure each other. Flash once, then run "
              "`python firmware/discover.py --router`, put it in config.yaml and build again.")


def build(c):
    idf = c["firmware"]["idf_path"]
    if not os.path.exists(os.path.join(idf, "export.sh")):
        sys.exit(f"ESP-IDF not found at {idf} — install v5.4/v5.5 (https://docs.espressif.com/projects/esp-idf) "
                 "or set firmware.idf_path in config.yaml")
    with open(os.path.join(HERE, "sdkconfig.defaults.kit")) as src, open(os.path.join(PROJ, "sdkconfig.defaults.kit"), "w") as dst:
        dst.write(src.read())
    overlays = ["sdkconfig.defaults"] + (["sdkconfig.defaults.devkitc"] if c["firmware"].get("devkitc", True) else []) + ["sdkconfig.defaults.kit"]
    d = ";".join(overlays)
    run(["bash", "-c", f'. "{idf}/export.sh" >/dev/null && rm -rf build sdkconfig && '
         f'idf.py -DSDKCONFIG_DEFAULTS="{d}" set-target esp32s3 && idf.py -DSDKCONFIG_DEFAULTS="{d}" build'], cwd=PROJ)
    print(f"\nbuilt: {os.path.join(PROJ, 'build', 'esp32-csi-node.bin')}\nnext:  python firmware/flash.py")


if __name__ == "__main__":
    c = kitconfig.load()
    fetch(); kit_header(c); build(c)
